"""Regenerate every Nimbles asset, CREDITS.md and the preview sheets.  python3 tools/build_assets.py"""
import re, sys, collections
sys.path.insert(0,str(__import__('pathlib').Path(__file__).parent))
from common import *
import gen_cards, gen_games, gen_chars, gen_static, gen_sheets
def build():
    gen_cards.run(); gen_games.run(); gen_chars.run(); gen_static.run()
    credits()
    return gen_sheets.sheets()
ORIG='Original work for Nimbles (generated by tools/gen_*.py); same licence as the Nimbles repo (MIT-compatible)'
SKOLL='https://game-icons.net/1x1/skoll/chess-{}.html'
def credits():
    SRC=gen_static.SRC; rows=[]
    for p in sorted(A.rglob('*')):
        if not p.is_file(): continue
        rel=p.relative_to(A).as_posix()
        if rel in SRC: src,lic,note=SRC[rel]
        elif re.match(r'chess/pieces/[wb]-(\w+)\.svg',rel):
            n=re.match(r'chess/pieces/[wb]-(\w+)\.svg',rel).group(1)
            src,lic,note=SKOLL.format(n),'CC BY 3.0','Silhouette by Skoll / game-icons.net, restyled (palette fill, navy outline, white/navy variants). Credit required'
        else: src,lic,note=ORIG,'Original (MIT)',''
        rows.append((rel,src,lic,note))
    cnt=collections.Counter(r[0].split('/')[0] for r in rows)
    out=['# Nimbles asset credits','',f'{len(rows)} files. Every file is listed in the table at the bottom with source and licence.','',
    '## Licence summary','',
    '| Licence | What | Obligation |','|---|---|---|',
    '| Original (MIT) | All SVG artwork drawn for Nimbles: cards, chess board, pool, sudoku, bubbles, word tiles, trivia UI, Last Bite, Pip, avatars, badges, effects, UI | None beyond the repo licence |',
    '| CC0 1.0 | Kenney audio packs (UI, interface, digital, casino, impact, music jingles) and two OpenGameArt music loops | None |',
    '| CC BY 3.0 | Chess piece silhouettes by Skoll from game-icons.net, restyled | **Credit required**: "Chess piece icons by Skoll, game-icons.net, CC BY 3.0 (https://creativecommons.org/licenses/by/3.0/)" in the app credits screen. Changes made: recoloured, outlined, white and navy variants |',
    '| ISC | Lucide icons (some derive from Feather, MIT) | Keep `icons/LICENSE-lucide.txt` |',
    '| SIL OFL 1.1 | Bricolage Grotesque, DM Mono | Keep the OFL text; fonts may not be sold on their own |','',
    '## Attribution text for the app credits screen','',
    '> Chess piece icons by Skoll from game-icons.net (CC BY 3.0). Sounds and music: Kenney (kenney.nl), Cleyton Kauffman and congusbongus via OpenGameArt (CC0). Icons: Lucide (ISC). Fonts: Bricolage Grotesque and DM Mono (SIL OFL 1.1).','',
    '## Palette','',
    'Brand: cream #F5F0E6, navy #1F2348, gold #F4B323, blue #1F78C4, coral #D0432E, green #1F8A5B. Extensions used by the assets: card #FFFCF5, raised #ECE5D5, sand #D9CFB4, chess dark square #A9CBE8, pink #F29AAE, purple #8E5CC0, orange #E9822A, brown #8A5A3C / #A9724A, silver and bronze for medals, plus edge shades and tints of the brand colours.','',
    '## Rejected','',
    'Kenney Playing Cards, Boardgame and Game Icons packs are CC0 but realistic or outlined in a different style, so their artwork was not used (original flat SVGs were drawn instead). Nothing non-commercial or of unclear licence is included.','',
    '## Count by folder','','| Folder | Files |','|---|---|']+[f'| {k} | {v} |' for k,v in sorted(cnt.items())]+['','## Files','','| File | Source | Licence | Note |','|---|---|---|---|']
    for r in rows: out.append('| '+' | '.join(x.replace('|','/') for x in r)+' |')
    (ROOT/'CREDITS.md').write_text('\n'.join(out)+'\n')
    # copy to assets too
    (A/'CREDITS.md').write_text('\n'.join(out)+'\n')
if __name__=='__main__': print(build())
